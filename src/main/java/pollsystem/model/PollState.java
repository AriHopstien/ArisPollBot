package pollsystem.model;

/** מצב מחזור החיים של הסקר, כדי שהממשק לעולם לא יישאר "עמום" (דגש UX, סעיף 4). */
public enum PollState {
    /** הסקר נוצר וממתין לשליחה מתוזמנת - זמן ה-Countdown (סעיף 4). */
    PENDING,
    /** הסקר נשלח בפועל למשתתפים והוא פעיל (סעיפים 6-10). */
    ACTIVE,
    /** הסקר נסגר - הזמן תם (5 דקות) או שכל המשתתפים השלימו (סעיף 9). */
    CLOSED
}
